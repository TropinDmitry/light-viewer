/**
 * Генерация тестовых IES-файлов (LM-63-2002) из формулы распределения.
 * Используется в тестах и в скрипте scripts/generate-ies.ts.
 */

export interface IesWriterOptions {
  catalogNumber: string;
  /** Описание для [LUMINAIRE]; лучше латиницей — старые программы не любят UTF-8. */
  description: string;
  /** Вертикальные углы γ, градусы. */
  verticalAngles: number[];
  /** Горизонтальные углы C, градусы ([0] — осесимметричный светильник). */
  horizontalAngles: number[];
  /** Сила света, кд, в направлении (γ, C). */
  intensity: (gammaDeg: number, cDeg: number) => number;
  /** Размеры светящей части, м. */
  widthM?: number;
  lengthM?: number;
  heightM?: number;
  inputWatts?: number;
}

export function writeIes(o: IesWriterOptions): string {
  const lines: string[] = [
    'IESNA:LM-63-2002',
    '[TEST] Generated by light-viewer (synthetic data, not a measurement)',
    '[TESTLAB] -',
    '[ISSUEDATE] 2026-10-28',
    '[MANUFAC] TEST',
    `[LUMCAT] ${o.catalogNumber}`,
    `[LUMINAIRE] ${o.description}`,
    'TILT=NONE',
    // число ламп, поток лампы (-1 = абсолютная фотометрия), множитель,
    // число верт. углов, число гор. углов, тип фотометрии (1 = C), единицы (2 = метры), ширина, длина, высота
    [1, -1, 1, o.verticalAngles.length, o.horizontalAngles.length, 1, 2, o.widthM ?? 0.1, o.lengthM ?? 0.1, o.heightM ?? 0.05].join(' '),
    // коэффициент балласта, резерв, мощность, Вт
    `1 1 ${o.inputWatts ?? 30}`,
    formatNumbers(o.verticalAngles),
    formatNumbers(o.horizontalAngles),
  ];
  for (const c of o.horizontalAngles) {
    lines.push(formatNumbers(o.verticalAngles.map((g) => o.intensity(g, c))));
  }
  return lines.join('\r\n') + '\r\n';
}

/** Числа по 10 в строке, как обычно в IES-файлах. */
function formatNumbers(values: number[]): string {
  const rows: string[] = [];
  for (let k = 0; k < values.length; k += 10) {
    rows.push(
      values
        .slice(k, k + 10)
        .map((v) => String(Math.round(v * 1000) / 1000))
        .join(' '),
    );
  }
  return rows.join('\r\n');
}

/** Равномерный ряд углов from…to с шагом step. */
export function angleRange(from: number, to: number, step: number): number[] {
  const out: number[] = [];
  for (let a = from; a <= to + 1e-9; a += step) out.push(Math.round(a * 1000) / 1000);
  return out;
}
